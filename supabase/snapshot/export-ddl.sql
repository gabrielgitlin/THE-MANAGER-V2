-- Builds a plain-SQL snapshot of the public schema from the catalog (read-only).
with tbl as (
  select c.oid, c.relname, c.relrowsecurity
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'r'
),
cols as (
  select t.relname,
         string_agg(
           format('  %I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
             case when a.attidentity = 'a' then ' generated always as identity'
                  when a.attidentity = 'd' then ' generated by default as identity' else '' end,
             case when a.attgenerated = 's' then format(' generated always as (%s) stored', pg_get_expr(d.adbin, d.adrelid))
                  when d.adbin is not null then ' default ' || pg_get_expr(d.adbin, d.adrelid) else '' end,
             case when a.attnotnull then ' not null' else '' end),
           E',\n' order by a.attnum) as body
  from tbl t
  join pg_attribute a on a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped
  left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
  group by t.relname
),
seqs as (
  select string_agg(format('create sequence public.%I as %s;', c.relname, format_type(sq.seqtypid, null)), E'
' order by c.relname) s
  from pg_sequence sq join pg_class c on c.oid = sq.seqrelid join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public'
),
creates as (
  select string_agg(format(E'create table public.%I (\n%s\n);', relname, body), E'\n\n' order by relname) s from cols
),
pk_uq_ck as (
  select string_agg(format('alter table public.%I add constraint %I %s;', t.relname, con.conname, pg_get_constraintdef(con.oid)),
                    E'\n' order by t.relname, con.conname) s
  from pg_constraint con join tbl t on t.oid = con.conrelid
  where con.contype in ('p', 'u', 'c', 'x')
),
fks as (
  select string_agg(format('alter table public.%I add constraint %I %s;', t.relname, con.conname, pg_get_constraintdef(con.oid)),
                    E'\n' order by t.relname, con.conname) s
  from pg_constraint con join tbl t on t.oid = con.conrelid
  where con.contype = 'f'
),
idx as (
  select string_agg(pg_get_indexdef(i.indexrelid) || ';', E'\n' order by t.relname, ic.relname) s
  from pg_index i join tbl t on t.oid = i.indrelid join pg_class ic on ic.oid = i.indexrelid
  where not exists (select 1 from pg_constraint con where con.conindid = i.indexrelid)
),
funcs as (
  select string_agg(pg_get_functiondef(p.oid) || ';', E'\n\n' order by p.proname) s
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind = 'f'
),
trg as (
  select string_agg(pg_get_triggerdef(tg.oid) || ';', E'\n' order by t.relname, tg.tgname) s
  from pg_trigger tg join tbl t on t.oid = tg.tgrelid
  where not tg.tgisinternal
),
rls as (
  select string_agg(format('alter table public.%I enable row level security;', relname), E'\n' order by relname) s
  from tbl where relrowsecurity
),
pol as (
  select string_agg(
    format('create policy %I on public.%I as %s for %s to %s%s%s;', policyname, tablename, permissive, cmd,
           array_to_string(roles, ', '),
           case when qual is not null then ' using (' || qual || ')' else '' end,
           case when with_check is not null then ' with check (' || with_check || ')' else '' end),
    E'\n' order by tablename, policyname) s
  from pg_policies where schemaname = 'public'
)
select concat_ws(E'\n\n',
  '-- ===== sequences =====', (select s from seqs),
  '-- ===== tables =====', (select s from creates),
  '-- ===== primary keys, unique, check =====', (select s from pk_uq_ck),
  '-- ===== foreign keys =====', (select s from fks),
  '-- ===== indexes =====', (select s from idx),
  '-- ===== functions =====', (select s from funcs),
  '-- ===== triggers =====', (select s from trg),
  '-- ===== row level security =====', (select s from rls),
  '-- ===== policies =====', (select s from pol)
) as ddl;
